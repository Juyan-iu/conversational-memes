#!/usr/bin/env python3
"""
Text-only caption probe (hypothesis B diagnosis).

Question: can a model identify the lexical distractor from CAPTION TEXT ALONE,
with no images and no conversation? If yes, the residual artifact signal lives
in the caption content (keyword-pasted text reads unnatural), not in rendering.

Uses each item's meta/OCR captions where available; falls back to running OCR
is NOT done here — we use the caption text stored in the benchmark metadata.

Usage:
  python caption_text_probe.py --data-root data/vlmeval_neutralized_v2 \
      --provider openai --model gpt-4o --sample 200 --seed 0

Checkpoint: caption_probe_<provider>_<model>.json (resumable).
"""
import argparse, json, random, sys, time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from runners.base import load_dataset, extract_letter

PROBE_PROMPT = (
    "Below are the caption texts from four internet memes, labeled A, B, C, and D.\n\n"
    "Exactly ONE of these captions was artificially generated by pasting extracted "
    "keywords into a template, rather than written by a person. Such captions often "
    "read as disconnected keywords instead of a natural phrase or joke.\n\n"
    "{captions}\n\n"
    "Which caption (A, B, C, or D) is the artificially generated one?\n"
    "Respond with ONLY one letter. Do NOT explain."
)


def get_captions_by_letter(item):
    """Pull per-option caption text from the item's metadata if present."""
    # load_dataset items carry meta with OCR captions per option file; adapt to
    # whatever fields exist. We try common layouts and give up gracefully.
    caps = {}
    meta = getattr(item, "meta", None) or {}
    per_option = meta.get("option_captions") or meta.get("captions_by_option")
    if per_option:
        # keys may be filenames; map through letter assignment
        for letter, fname in getattr(item, "file_by_letter", {}).items():
            if fname in per_option:
                caps[letter] = per_option[fname]
    return caps


def ask_openai(model, captions_block):
    from openai import OpenAI
    client = OpenAI()
    resp = client.chat.completions.create(
        model=model,
        messages=[{"role": "user",
                   "content": PROBE_PROMPT.format(captions=captions_block)}],
        max_tokens=10, temperature=0)
    return resp.choices[0].message.content.strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-root", required=True)
    ap.add_argument("--provider", choices=["openai"], default="openai")
    ap.add_argument("--model", default="gpt-4o")
    ap.add_argument("--sample", type=int, default=200)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    items = load_dataset(args.data_root, seed=args.seed)
    items = [it for it in items if "lexical" in it.slot_type_by_letter.values()]
    rng = random.Random(42)
    items = sorted(items, key=lambda it: it.id)
    if args.sample and args.sample < len(items):
        items = rng.sample(items, args.sample)
    print(f"[LOAD] {len(items)} items")

    # Caption source check on the first item
    probe_via_meta = bool(get_captions_by_letter(items[0]))
    if not probe_via_meta:
        print("[INFO] per-option caption metadata not found on items;")
        print("       falling back to OCR-on-the-fly is NOT implemented here.")
        print("       -> Run with --easyocr to extract captions now.")
        # implement lightweight on-the-fly OCR fallback
        try:
            import easyocr
        except ImportError:
            sys.exit("Install easyocr in this env, or run from the 04_benchmark env: pip install easyocr")
        reader = easyocr.Reader(["en"], gpu=True)
        def ocr_caption(path):
            res = reader.readtext(str(path), detail=0)
            return " ".join(res)[:300]
    out_path = Path(f"caption_probe_{args.provider}_{args.model}.json")
    done = json.loads(out_path.read_text()) if out_path.exists() else {}

    for i, it in enumerate(items, 1):
        if it.id in done:
            continue
        gold = next(l for l, t in it.slot_type_by_letter.items() if t == "lexical")
        caps = get_captions_by_letter(it)
        if not caps:
            caps = {l: ocr_caption(it.images[l]) for l in "ABCD"}
        if any(not caps.get(l, "").strip() for l in "ABCD"):
            done[it.id] = {"pred": "SKIP:empty-caption", "gold_lexical": gold}
            continue
        block = "\n".join(f'{l}: "{caps[l].strip()}"' for l in "ABCD")
        for attempt in range(4):
            try:
                raw = ask_openai(args.model, block)
                done[it.id] = {"pred": extract_letter(raw) or "?", "gold_lexical": gold}
                break
            except Exception as e:
                if any(s in str(e).lower() for s in ("rate", "429", "timeout", "500", "503")):
                    time.sleep(2 ** attempt); continue
                done[it.id] = {"pred": f"ERR:{e}"[:60], "gold_lexical": gold}
                break
        if i % 20 == 0:
            out_path.write_text(json.dumps(done, indent=2))
            print(f"  {i}/{len(items)}")
    out_path.write_text(json.dumps(done, indent=2))

    v = [(x["pred"], x["gold_lexical"]) for x in done.values() if x["pred"] in "ABCD"]
    k = sum(p == g for p, g in v)
    print(f"\n[RESULT] text-only caption detection: {k}/{len(v)} = {k/len(v):.3f} (chance 0.25)")
    try:
        from scipy import stats
        print(f"         binomial p = {stats.binomtest(k, len(v), 0.25, alternative='greater').pvalue:.4f}")
        print("         above chance -> residual signal lives in CAPTION CONTENT (hypothesis B confirmed)")
    except ImportError:
        pass


if __name__ == "__main__":
    main()
