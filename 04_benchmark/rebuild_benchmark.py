#!/usr/bin/env python3
"""
Full benchmark rebuild for MEMECONV (corrected construction).

Applies, per item, the three corrections validated on the 200-item pilot:
  1. NEUTRALIZE  : gold meme + easy(random) distractor pass through the
                   identical inpaint-and-render pipeline (own captions kept)
  2. NATURALIZE  : lexical distractor caption regenerated by an LLM
                   (topic words kept, phrased like human writing), re-rendered
  3. RE-ENCODE   : all four option images re-saved with identical JPEG params

Pilot validation: artifact detection 45.5% (original) -> 27.5% (corrected),
p=.229 vs 25% chance.

Run from 04_benchmark, inside the env that has easyocr + lama (bench_env):
  pip install openai
  export OPENAI_API_KEY=...
  nohup python -u rebuild_benchmark.py \
      --src ../05_benchmark_evaluation/data/vlmeval_converted \
      --out ../05_benchmark_evaluation/data/vlmeval_corrected \
      > rebuild.log 2>&1 &

Resumable: items with a REBUILD.json marker are skipped on re-run.
Validate afterwards from 05_benchmark_evaluation:
  python artifact_probe.py --provider openai --model gpt-4o \
      --sample 500 --seed 0 --data-root data/vlmeval_corrected
"""
import argparse, json, re, shutil, sys, time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from PIL import Image
from benchmark_pipeline import (extract_captions, analyze_caption_style,
                                inpaint_captions, draw_caption_at_bbox)

IMG_EXTS = {".jpg", ".jpeg", ".png", ".webp"}

GEN_PROMPT = (
    "You write short internet meme captions.\n\n"
    "Conversation:\n{conv}\n\n"
    "Write ONE short meme caption (under 8 words) that uses one or two key "
    "words from this conversation's topic, but would be a WRONG reply to this "
    "specific conversation: it should take a clearly different stance, "
    "emotion, or situation than the conversation calls for. It must still "
    "read like a caption a real person would write. Do not use quotes. Do "
    "not explain. Output the caption only."
)


def natural_caption(client, model, conv):
    resp = client.chat.completions.create(
        model=model,
        messages=[{"role": "user", "content": GEN_PROMPT.format(conv=conv[:1500])}],
        max_completion_tokens=40)
    cap = (resp.choices[0].message.content or "").strip().strip('"').strip()
    return re.sub(r"\s+", " ", cap)[:70]


def rerender_own_caption(img):
    """Inpaint existing captions and redraw the SAME text (neutralization)."""
    captions = extract_captions(img)
    if not captions:
        return None, 0
    styles = [analyze_caption_style(img, c) for c in captions]
    result = inpaint_captions(img, captions)
    for cap, style in zip(captions, styles):
        result = draw_caption_at_bbox(result, cap["text"], style=style)
    return result, len(captions)


def rerender_new_caption(img, new_text):
    """Inpaint existing captions and draw NEW text at the largest bbox."""
    captions = extract_captions(img)
    if not captions:
        return None
    styles = [analyze_caption_style(img, c) for c in captions]
    largest = max(range(len(captions)),
                  key=lambda j: (captions[j]["bbox"][2] - captions[j]["bbox"][0])
                                * (captions[j]["bbox"][3] - captions[j]["bbox"][1]))
    result = inpaint_captions(img, captions)
    result = draw_caption_at_bbox(result, new_text, style=styles[largest])
    return result


def uniform_save(img, path, quality):
    """Save as .jpg with identical params; return the (possibly new) path."""
    target = path.with_suffix(".jpg")
    img.convert("RGB").save(target, "JPEG", quality=quality, optimize=True)
    if target != path and path.exists():
        path.unlink()
    return target


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--gen-model", default="gpt-5.4-mini")
    ap.add_argument("--quality", type=int, default=90)
    ap.add_argument("--limit", type=int, default=None, help="process first N items only (testing)")
    ap.add_argument("--ids", default=None,
                    help="path to a txt file of item ids (one per line); only these are rebuilt")
    args = ap.parse_args()

    from openai import OpenAI
    client = OpenAI()

    src, out = Path(args.src), Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    dirs = sorted(p for p in src.iterdir() if p.is_dir())
    if args.ids:
        keep = set(Path(args.ids).read_text().split())
        dirs = [d for d in dirs if d.name in keep]
        print(f"[IDS] restricted to {len(dirs)} items from {args.ids}", flush=True)
    if args.limit:
        dirs = dirs[:args.limit]
    print(f"[REBUILD] {len(dirs)} items -> {out}", flush=True)

    stats = {"full": 0, "gold_no_captions": 0, "random_no_captions": 0,
             "lexical_no_captions": 0, "gen_failed": 0, "skipped": 0}

    for i, d in enumerate(dirs, 1):
        dst = out / d.name
        if dst.exists() and (dst / "REBUILD.json").exists():
            continue
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(d, dst)

        labels_path = dst / "labels.json"
        gold = next((p for p in dst.iterdir()
                     if p.stem == d.name and p.suffix.lower() in IMG_EXTS), None)
        if gold is None or not labels_path.exists():
            stats["skipped"] += 1
            print(f"  [skip] {d.name}: missing gold or labels", flush=True)
            shutil.rmtree(dst)
            continue
        labels = json.loads(labels_path.read_text())
        by_slot = {slot: dst / fname for fname, slot in labels.items()}
        record = {"uid": d.name}

        # 1) NEUTRALIZE gold: if no captions detected, drop item (paper: 100%
        #    of items have OCR captions on gold, so this should be rare)
        img = Image.open(gold).convert("RGB")
        neut, ncap = rerender_own_caption(img)
        if neut is None:
            stats["gold_no_captions"] += 1
            print(f"  [drop] {d.name}: no captions on gold", flush=True)
            shutil.rmtree(dst)
            continue
        gold_new = uniform_save(neut, gold, args.quality)
        record["gold"] = {"neutralized": True, "captions": ncap}

        # 1b) NEUTRALIZE easy/random distractor (best effort)
        rand = by_slot.get("random")
        if rand is not None and rand.exists():
            rimg = Image.open(rand).convert("RGB")
            rneut, rncap = rerender_own_caption(rimg)
            if rneut is not None:
                rand_new = uniform_save(rneut, rand, args.quality)
                record["random"] = {"neutralized": True, "captions": rncap,
                                    "file": rand_new.name}
            else:
                stats["random_no_captions"] += 1
                rand_new = uniform_save(rimg, rand, args.quality)
                record["random"] = {"neutralized": False, "file": rand_new.name}

        # 2) NATURALIZE lexical distractor caption
        lex = by_slot.get("lexical")
        lex_ok = False
        if lex is not None and lex.exists():
            conv = re.sub(r"\[Tone:.*?\]", "",
                          (dst / "info.txt").read_text(errors="ignore"))
            cap_text = None
            for attempt in range(3):
                try:
                    cap_text = natural_caption(client, args.gen_model, conv)
                    if cap_text:
                        break
                except Exception:
                    time.sleep(2 ** attempt)
            if not cap_text:
                stats["gen_failed"] += 1
                record["lexical"] = {"naturalized": False, "reason": "gen_failed"}
            else:
                limg = Image.open(lex).convert("RGB")
                lnew = rerender_new_caption(limg, cap_text)
                if lnew is None:
                    stats["lexical_no_captions"] += 1
                    record["lexical"] = {"naturalized": False,
                                         "reason": "no_captions"}
                    lex_new = uniform_save(limg, lex, args.quality)
                else:
                    lex_new = uniform_save(lnew, lex, args.quality)
                    record["lexical"] = {"naturalized": True,
                                         "new_caption": cap_text,
                                         "file": lex_new.name}
                    lex_ok = True

        # 3) RE-ENCODE remaining option (visual distractor) identically
        vis = by_slot.get("visual")
        if vis is not None and vis.exists():
            vimg = Image.open(vis).convert("RGB")
            vis_new = uniform_save(vimg, vis, args.quality)
            record["visual"] = {"file": vis_new.name}

        # labels.json keys: everything is .jpg now
        labels = {Path(k).stem + ".jpg": v for k, v in labels.items()}
        labels_path.write_text(json.dumps(labels))

        if record["gold"]["neutralized"] and record.get("random", {}).get("neutralized") and lex_ok:
            stats["full"] += 1
        (dst / "REBUILD.json").write_text(json.dumps(record, ensure_ascii=False))

        if i % 50 == 0:
            print(f"  {i}/{len(dirs)}  {stats}", flush=True)

    # manifest
    manifest = []
    for d in sorted(p for p in out.iterdir() if p.is_dir()):
        m = d / "REBUILD.json"
        if m.exists():
            manifest.append(json.loads(m.read_text()))
    (out / "rebuild_manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=1))
    print(f"\n[DONE] {stats}")
    print(f"items in corrected tree: {len(manifest)}")
    print(f"fully corrected (all three steps): {stats['full']}")
    print(f"manifest -> {out/'rebuild_manifest.json'}")
    print("\nNext: spot-check ~20 items visually, then run the acceptance probe:")
    print("  python artifact_probe.py --provider openai --model gpt-4o \\")
    print("      --sample 500 --seed 0 --data-root data/vlmeval_corrected")


if __name__ == "__main__":
    main()
